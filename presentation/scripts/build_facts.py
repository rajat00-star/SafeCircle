"""Collect every number the deck and the site quote, straight from the committed result files.

    python3 presentation/scripts/build_facts.py

Writes presentation/content/facts.json and presentation/site/data/facts.js. Nothing is typed in by hand
except the test-run results, which are read from presentation/content/test-results.json (filled from real runs).
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / "evaluation"


def load(p: str) -> dict:
    return json.loads((EV / p).read_text())


def system(m: dict) -> dict:
    return {"tp": m["tp"], "fp": m["fp"], "tn": m["tn"], "fn": m["fn"],
            "precision": m["precision"], "recall": m["recall"], "fpr": m["false_positive_rate"], "f1": m.get("f1")}


def errors(rows: list[dict]) -> list[dict]:
    out = []
    for r in rows:
        if r["label"] in ("scam", "benign") and r["flagged"] != (r["label"] == "scam"):
            out.append({"id": r["id"], "type": "false_positive" if r["label"] == "benign" else "false_negative",
                        "description": r["description"], "outcome": r["outcome"], "score": r["score"]})
    return out


def holdout(p: str, source: str, note: str) -> dict:
    d = load(p)
    m = d["metrics"]
    return {"source": source, "note": note, "dataset_sha256": m["dataset_sha256"], "scenarios": m["scenarios"],
            "binary_scored": m["binary_scored"], "scam": m["scam"], "benign": m["benign"], "ambiguous": m["ambiguous"],
            "integration_only": m["integration_only"], "safecircle": system(m["safecircle"]),
            "keyword_baseline": system(m["baseline_keyword"]), "single_message_detector": system(m["baseline_legacy_detector"]),
            "acceptable_outcome": m.get("acceptable_outcome_rate"), "alerts": m.get("alerts"),
            "latency_ms_per_event_inprocess": m.get("latency_ms_per_event_api_inprocess"), "errors": errors(d["rows"])}


def main() -> None:
    detector = json.loads((EV / "results" / "metrics.json").read_text())
    tests_file = ROOT / "presentation" / "content" / "test-results.json"
    facts = {
        "_about": "Generated by presentation/scripts/build_facts.py from committed evaluation files. "
                  "All benchmark data is synthetic DEMO DATA written by the SafeCircle team; synthetic results "
                  "do not establish real-world fraud-detection accuracy.",
        "v2": holdout("holdout_v2/results_v2_baseline.json", "evaluation/holdout_v2/results_v2_baseline.json",
                      "Frozen before the first run; rules unchanged for the run; not used for tuning."),
        "v2_post_hardening": holdout("holdout_v2/results_v2_posthardening.json",
                                     "evaluation/holdout_v2/results_v2_posthardening.json",
                                     "Re-run after hardening for information only; not independent."),
        "v3_before": holdout("holdout_v3/results_v3_prefix.json", "evaluation/holdout_v3/results_v3_prefix.json",
                             "Frozen before the hardening fixes; author had read the rules and v2 errors, so not an independent benchmark."),
        "v3_after": holdout("holdout_v3/results_v3_postfix.json", "evaluation/holdout_v3/results_v3_postfix.json",
                            "Same set after hardening; not used for tuning."),
        "single_message_detector_public_data": {
            "source": "evaluation/results/metrics.json",
            "note": "Original single-message detector on public data (SMS Spam Collection test split; reported phishing "
                    "URLs vs popular hostnames). Held out but not fully blind. Generic spam/phishing, not UPI scams.",
            "raw": detector},
        "tests": json.loads(tests_file.read_text()) if tests_file.exists() else None,
    }
    facts["fingerprint"] = hashlib.sha256(json.dumps(facts, sort_keys=True).encode()).hexdigest()[:12]
    (ROOT / "presentation" / "content" / "facts.json").write_text(json.dumps(facts, indent=1) + "\n")
    (ROOT / "presentation" / "site" / "data" / "facts.js").write_text("window.FACTS = " + json.dumps(facts) + ";\n")
    v2 = facts["v2"]["safecircle"]
    print(f"v2 P {v2['precision']['value']} R {v2['recall']['value']} FPR {v2['fpr']['value']}; fingerprint {facts['fingerprint']}")


if __name__ == "__main__":
    main()
